"""One living file with every query and its latest score per metric.

``evals/scorebook.json`` is the store (id -> metric -> score, run label, time).
``evals/SCOREBOOK.md`` is regenerated from it after every update. A run only
overwrites the metrics it actually produced, so a faithfulness-only run leaves
recall, precision and the rest as they were. Scores that are ``None`` (judge
error, row skipped) never replace an earlier value.

Scripts call :func:`update`. To rebuild the markdown by hand:

    uv run python -m evals.scorebook
"""

from __future__ import annotations

import json
import os
from collections.abc import Iterable
from datetime import UTC, datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
STORE = ROOT / "evals" / "scorebook.json"
REPORT = ROOT / "evals" / "SCOREBOOK.md"
GOLDENS = ROOT / "evals" / "retriever_goldens.json"

METRICS = ("recall", "precision", "relevancy", "faithfulness", "answer_relevancy", "correctness")
# Multilingual diagnostics (ids prefixed `ml-`); shown in their own table, never in the means above.
ML_METRICS = ("routing_ok", "evidence_hit", "cross_language", "ambiguity_ok", "grounded", "intent_preserved")
SHORT = {
    "routing_ok": "routing ok",
    "evidence_hit": "evidence hit",
    "cross_language": "cross-lang",
    "ambiguity_ok": "ambiguity ok",
    "grounded": "grounded",
    "intent_preserved": "intent kept",
    "recall": "recall",
    "precision": "precision",
    "relevancy": "ctx relevancy",
    "faithfulness": "faithfulness",
    "answer_relevancy": "answer relevancy",
    "correctness": "correctness",
}
# Names used by the retriever judge.
ALIASES = {
    "ContextualRecallMetric": "recall",
    "ContextualPrecisionMetric": "precision",
    "ContextualRelevancyMetric": "relevancy",
}
LOW = 0.7


def _load() -> dict[str, Any]:
    return json.loads(STORE.read_text(encoding="utf-8")) if STORE.exists() else {}


def update(run: str, rows: Iterable[dict[str, Any]], *, write: bool = True) -> int:
    """Merge one run into the store. Each row: ``{"id", "query"?, "scores": {metric: float|None}}``.

    Returns how many (id, metric) values changed.
    """
    if os.getenv("QUE_SCOREBOOK_OFF"):  # experiments (benchmarks) must not overwrite latest scores
        return 0
    store = _load()
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M")
    changed = 0
    for row in rows:
        rid = row.get("id")
        if not rid:
            continue
        entry = store.setdefault(rid, {"query": row.get("query", ""), "metrics": {}})
        if row.get("query"):
            entry["query"] = row["query"]
        for name, score in (row.get("scores") or {}).items():
            name = ALIASES.get(name, name)
            if name not in METRICS + ML_METRICS or not isinstance(score, (int, float)):
                continue
            score = round(float(score), 3)
            old = entry["metrics"].get(name)
            if old is None or old["score"] != score:
                changed += 1
            entry["metrics"][name] = {"score": score, "run": run, "at": now}
    if write:
        STORE.write_text(json.dumps(store, indent=2, ensure_ascii=False), encoding="utf-8")
        render(store)
    return changed


def _cell(m: dict[str, Any] | None) -> str:
    if not m:
        return "–"
    s = m["score"]
    return f"**{s:.2f}**" if s < LOW else f"{s:.2f}"


def render(store: dict[str, Any] | None = None) -> Path:
    store = store if store is not None else _load()
    order = []
    if GOLDENS.exists():
        order = [g["id"] for g in json.loads(GOLDENS.read_text(encoding="utf-8"))["goldens"] if not g.get("rejected")]
    ml_ids = [i for i in store if i.startswith("ml-")]
    ids = [i for i in order if i in store] + [i for i in store if i not in order and not i.startswith("ml-")]

    means = {}
    for name in METRICS:
        vals = [store[i]["metrics"][name]["score"] for i in ids if name in store[i]["metrics"]]
        means[name] = (round(sum(vals) / len(vals), 3), len(vals)) if vals else None

    lines = [
        "# Scorebook: every query, latest score per metric",
        "",
        "Generated by `evals/scorebook.py` from `evals/scorebook.json`. Do not edit by hand: each eval run "
        "overwrites only the metrics it produced. **Bold** = below "
        f"{LOW}. `–` = never scored. Last run per metric is in the lower table.",
        "",
        "| metric | mean | rows scored |",
        "|---|---|---|",
    ]
    for name in METRICS:
        m = means[name]
        lines.append(f"| {SHORT[name]} | {m[0]:.3f} | {m[1]} |" if m else f"| {SHORT[name]} | – | 0 |")

    full = sum(all(n in store[i]["metrics"] for n in METRICS) for i in ids)
    lines += [
        "",
        f"Coverage: {full} of {len(ids)} retriever-golden rows have all six metrics. The rest were never run through the "
        "answer-level judge (faithfulness / answer relevancy / correctness need a generated answer); they show –, not 0.",
    ]
    lines += ["", "| id | query | " + " | ".join(SHORT[n] for n in METRICS) + " | low |", "|---|---|" + "---|" * (len(METRICS) + 1)]
    for rid in ids:
        e = store[rid]
        low = [SHORT[n] for n in METRICS if n in e["metrics"] and e["metrics"][n]["score"] < LOW]
        cells = " | ".join(_cell(e["metrics"].get(n)) for n in METRICS)
        lines.append(f"| {rid} | {e['query'][:60].replace('|', '/')} | {cells} | {len(low) or ''} |")

    if ml_ids:
        lines += [
            "",
            "## Multilingual / informal cases (evals/multilingual_cases.json, provisional)",
            "",
            "Diagnostic metrics, not DeepEval. – = N/A or not scored (never 0). routing/evidence/cross-lang/ambiguity are "
            "deterministic (local MiniLM index, current code); grounded / intent kept are one judge call per answer and are "
            "only kept where the answer was generated by the current routing.",
            "",
            "| id | query | " + " | ".join(SHORT[n] for n in ML_METRICS) + " |",
            "|---|---|" + "---|" * len(ML_METRICS),
        ]
        for rid in ml_ids:
            e = store[rid]
            cells = " | ".join(_cell(e["metrics"].get(n)) for n in ML_METRICS)
            lines.append(f"| {rid} | {e['query'][:60].replace('|', '/')} | {cells} |")

    latest: dict[str, tuple[str, str]] = {}
    for rid, e in store.items():
        if rid.startswith("ml-"):
            continue
        for name, m in e["metrics"].items():
            if name not in latest or m["at"] > latest[name][1]:
                latest[name] = (m["run"], m["at"])
    lines += ["", "## Last update per metric", "", "| metric | run | time (UTC) |", "|---|---|---|"]
    for name in METRICS:
        if name in latest:
            lines.append(f"| {SHORT[name]} | {latest[name][0]} | {latest[name][1]} |")
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return REPORT


if __name__ == "__main__":
    print("wrote", render())
